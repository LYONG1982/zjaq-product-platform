declare const wx: { env: { USER_DATA_PATH: string } };
type Slot = "banner" | `banner-${string}` | "official-qr" | "service-qr";
type FileSystem = {
  writeFile(options: { filePath: string; data: string; encoding: "base64"; success: () => void; fail: () => void }): void;
  unlink(options: { filePath: string; success?: () => void; fail: () => void }): void;
  readdir?(options: { dirPath: string; success: (result: { files: string[] }) => void; fail: () => void }): void;
};
declare const uni: { getFileSystemManager(): FileSystem };
type Entry = { version: number; source: string | null; path: string | null; task?: Promise<string | null> };
/** Each slot retains removal versions and gives concurrent writes unique destinations. */
export function createSiteImageResolver(fs: FileSystem, root: string) {
  const entries = new Map<Slot, Entry>(); let sequence = 0;
  // A fresh JS process has no consumers of files left by a previous launch.
  // Remove only names generated by this helper, one file at a time.
  const startup = fs.readdir ? new Promise<void>(resolve => fs.readdir!({ dirPath: root, fail: resolve, success: result => {
    void (async () => {
      for (const name of result.files) if (/^zj-(?:banner(?:-[a-zA-Z0-9_-]+)?|official-qr|service-qr)-\d+(?:-\d+)?\.(?:png|jpg)$/.test(name)) await new Promise<void>(done => fs.unlink({ filePath: root + "/" + name, success: done, fail: done }));
    })().then(resolve, resolve);
  } })) : undefined;
  const unlink = (path: string | null) => { if (path) fs.unlink({ filePath: path, fail() {} }); };
  return async (data: string | null, slot: Slot, version: number): Promise<string | null> => {
    if (startup) await startup;
    if (!Number.isSafeInteger(version) || version < 0) return null;
    const prior = entries.get(slot);
    if (prior && prior.version > version) return null;
    if (prior && prior.version === version && prior.source === data) {
      if (prior.task) return prior.task;
      if (prior.path || !data) return prior.path;
    }
    const entry: Entry = { version, source: data, path: null };
    entries.set(slot, entry);
    if (!data) { unlink(prior?.path ?? null); return null; }
    const match = data.match(/^data:image\/(png|jpeg);base64,([A-Za-z0-9+/]+={0,2})$/);
    if (!match || match[2].length > 600000) { unlink(prior?.path ?? null); return null; }
    const path = `${root}/zj-${slot}-${version}-${++sequence}.${match[1] === "jpeg" ? "jpg" : "png"}`;
    entry.task = (async () => {
      try { await new Promise<void>((resolve, reject) => fs.writeFile({ filePath: path, data: match[2], encoding: "base64", success: resolve, fail: () => reject(new Error("配置图片读取失败")) })); }
      catch { unlink(path); unlink(prior?.path ?? null); return null; }
      if (entries.get(slot) !== entry) { unlink(path); return null; }
      entry.path = path; unlink(prior?.path ?? null); return path;
    })();
    try { return await entry.task; } finally { entry.task = undefined; }
  };
}
let nativeResolver: ReturnType<typeof createSiteImageResolver> | undefined;
/** Native WeChat images use local files rather than relying on data URI support. */
export async function siteImagePath(data: string | null, slot: Slot, version: number): Promise<string | null> {
  // #ifdef MP-WEIXIN
  nativeResolver ??= createSiteImageResolver(uni.getFileSystemManager(), wx.env.USER_DATA_PATH);
  return nativeResolver(data, slot, version);
  // #endif
  // #ifdef H5
  return data;
  // #endif
}
