import { test, expect, urls, json, publicProductId } from "./support";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";

test("administrator safely removes with conflict protection, views retained history, restores and explicitly republishes", async ({ page, request }) => {
  const name = "【浏览器移除】" + Date.now();
  const created = (await json(request, "/admin/products", "POST", { name, categoryId: "ai", templateId: "ai", templateVersion: 1, owner: "虚构验证人员", model: "REMOVE-UI-" + randomUUID(), productType: "SOFTWARE", ownership: "SELF_DEVELOPED" }, randomUUID())).body.data;
  const bytes = await readFile("tests/fixtures/validation/sample-v1.pdf");
  const intent = (await json(request, "/admin/uploads", "POST", { productId: created.productId, purpose: "preview", fileName: "removal-test.pdf", contentType: "application/pdf", size: bytes.length }, randomUUID())).body.data;
  await request.put(urls.api + intent.uploadPath, { headers: { Authorization: "Bearer local-mock", "Content-Type": "application/octet-stream" }, data: bytes });
  const upload = (await json(request, "/admin/uploads/complete", "POST", { uploadId: intent.uploadId })).body.data;
  expect(upload.status).toBe("READY");
  const item = { id: "one", title: "本地测试", text: "虚构正文" };
  const content = { ...created.content, tagline: "虚构验证", summary: "仅本地测试", problemValues: [item], features: [item], scenarios: [item], technical: { inputs: "文档", outputs: "草稿", humanReview: "人工" }, materials: [{ materialId: "removal-fixture", versionId: randomUUID(), name: "【留档】移除验证资料", kind: "brochure", category: "promotional", subCategory: "deck", versionLabel: "V1.0", preview: { kind: "pdf", assetId: upload.assetId, pageCount: 2 } }] };
  let saved = (await json(request, `/admin/products/${created.productId}/draft`, "PATCH", { expectedDraftVersion: 1, content })).body.data;
  const published = (await json(request, `/admin/products/${created.productId}/publish`, "POST", { expectedDraftVersion: saved.draftVersion, expectedPublicationVersion: 0, publicContentConfirmed: true }, randomUUID())).body.data;
  const publicId = await publicProductId(request, name, published.releaseId);
  await page.goto(urls.admin);
  await page.getByLabel("搜索产品", { exact: true }).fill(name);
  await page.getByRole("button", { name: "查询", exact: true }).click();
  const row = page.locator("tbody tr").filter({ hasText: name });
  await expect(row).toHaveCount(1);
  await row.getByRole("button", { name: "移除产品", exact: true }).click();
  let modal = page.getByRole("dialog", { name: "确认移除产品", exact: true });
  await expect(modal.getByRole("button", { name: "确认移除", exact: true })).toBeDisabled();
  await modal.getByLabel("移除原因（必填）", { exact: true }).fill("虚构验证结束，保留历史和原件");
  await modal.getByRole("checkbox").check();
  saved = (await json(request, `/admin/products/${created.productId}/draft`, "PATCH", { expectedDraftVersion: saved.draftVersion, content: { ...content, summary: "另一个窗口保存" } })).body.data;
  await modal.getByRole("button", { name: "确认移除", exact: true }).click();
  await expect(modal.getByRole("alert")).toContainText("草稿已变化");
  await expect(modal.getByLabel("移除原因（必填）", { exact: true })).toHaveValue("虚构验证结束，保留历史和原件");
  await modal.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByRole("button", { name: "查询", exact: true }).click();
  await row.getByRole("button", { name: "移除产品", exact: true }).click();
  modal = page.getByRole("dialog", { name: "确认移除产品", exact: true });
  await modal.getByLabel("移除原因（必填）", { exact: true }).fill("虚构验证结束，保留历史和原件");
  await modal.getByRole("checkbox").check();
  await modal.getByRole("button", { name: "确认移除", exact: true }).click();
  await expect(row).toHaveCount(0);
  expect((await request.get(urls.api + `/api/v1/catalog/products/${publicId}`)).status()).toBe(404);
  await page.getByLabel("移除状态", { exact: true }).selectOption("true");
  await expect(row).toHaveCount(1);
  await expect(row.getByText("已移除 · 虚构验证结束，保留历史和原件")).toBeVisible();
  await row.getByRole("button", { name: "查看留档", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "发布", exact: true })).toBeDisabled();
  await expect(page.getByLabel("产品简介", { exact: false })).toBeDisabled();
  await page.getByRole("button", { name: "查看历史版本", exact: true }).click();
  const history = page.getByRole("dialog", { name: "资料历史版本", exact: true });
  await expect(history.getByText(/移除验证资料 · V1\.0/)).toBeVisible();
  await history.getByRole("button", { name: "预览", exact: true }).click();
  const preview = page.getByRole("dialog", { name: /历史预览/ }); await expect(preview.locator("canvas")).toBeVisible();
  await preview.getByRole("button", { name: "关闭预览", exact: true }).click();
  await history.getByRole("button", { name: "关闭", exact: true }).click();
  await page.getByRole("button", { name: "← 返回产品管理", exact: true }).click();
  await row.getByRole("button", { name: "恢复产品", exact: true }).click();
  const restore = page.getByRole("dialog", { name: "确认恢复产品", exact: true });
  await restore.getByLabel("恢复原因（必填）", { exact: true }).fill("继续维护虚构验证产品"); await restore.getByRole("checkbox").check();
  await restore.getByRole("button", { name: "确认恢复", exact: true }).click();
  await expect(row).toHaveCount(0);
  expect((await request.get(urls.api + `/api/v1/catalog/products/${publicId}`)).status()).toBe(404);
  await page.getByLabel("移除状态", { exact: true }).selectOption("");
  await expect(row.getByText("已下架", { exact: true })).toBeVisible();
  await row.getByRole("button", { name: "编辑", exact: true }).click();
  await page.getByRole("button", { name: "发布", exact: true }).click();
  const publish = page.getByRole("dialog", { name: "确认发布", exact: true }); await publish.getByRole("checkbox").check();
  await publish.getByRole("button", { name: "确认发布", exact: true }).click();
  await expect(page.getByText(/发布成功/)).toBeVisible();
  expect((await request.get(urls.api + `/api/v1/catalog/products/${publicId}`)).status()).toBe(200);
  await page.screenshot({ path: "work/round04/product-restored-republished.png", fullPage: true });
});
