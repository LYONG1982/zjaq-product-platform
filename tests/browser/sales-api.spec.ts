import { test, expect, urls } from "./support";

test("sales API restricts current preview and download to authenticated sales", async ({ request }) => {
  const api = urls.api + "/api/v1", headers = { Authorization: "Bearer local-sales" };
  const search = "/sales/catalog/products?q=" + encodeURIComponent("知识查询演示");
  expect((await request.get(api + search)).status()).toBe(401);
  expect((await request.get(api + search, { headers: { Authorization: "Bearer local-admin" } })).status()).toBe(403);
  const listed = await request.get(api + search, { headers });
  expect(listed.status()).toBe(200);
  const product = (await listed.json()).data.find((item: { name: string }) => item.name === "【Demo】资料问答助手");
  expect(product).toBeTruthy();
  expect(product.productId).not.toMatch(/^ZJ-/);
  const adminList = await request.get(api + "/admin/products?q=" + encodeURIComponent("【Demo】资料问答助手"), { headers: { Authorization: "Bearer local-mock" } });
  const internalId = (await adminList.json()).data[0].productId;
  expect(internalId).toMatch(/^ZJ-[DYSA]-[SH]-[AB]-\d{3}$/);
  expect((await request.get(api + "/catalog/products/" + internalId)).status()).toBe(404);
  const publicDetail = await request.get(api + "/catalog/products/" + product.productId);
  expect(publicDetail.status()).toBe(200);
  expect(JSON.stringify(await publicDetail.json())).not.toContain(internalId);
  const anonymousSearch = await request.get(api + "/catalog/products?q=" + encodeURIComponent("知识查询演示"));
  expect((await anonymousSearch.json()).data).toEqual([]);
  const path = `/sales/catalog/products/${product.productId}`;
  const detail = await request.get(api + path, { headers });
  expect(detail.status()).toBe(200);
  const material = (await detail.json()).data.materials.find((item: { materialId: string }) => item.materialId === "demo-introduction");
  expect(material).toBeTruthy();
  const manifestUrl = api + path + "/materials/demo-introduction/preview";
  expect((await request.get(manifestUrl)).status()).toBe(401);
  const manifest = (await (await request.get(manifestUrl, { headers })).json()).data;
  const preview = urls.api + manifest.parts[0].path;
  expect((await request.get(preview)).status()).toBe(401);
  expect((await request.get(preview, { headers })).status()).toBe(200);
  const downloadUrl = api + path + `/materials/demo-introduction/source?releaseId=${encodeURIComponent(manifest.releaseId)}&versionId=${encodeURIComponent(manifest.versionId)}`;
  expect((await request.get(downloadUrl)).status()).toBe(401);
  const download = await request.get(downloadUrl, { headers });
  expect(download.status()).toBe(200);
  expect(download.headers()["content-disposition"]).toMatch(/^attachment;/);
  expect((await download.body()).subarray(0, 4).toString()).toBe("%PDF");
  expect((await request.get(downloadUrl.replace(encodeURIComponent(manifest.versionId), "stale"), { headers })).status()).toBe(409);
});
